-- =====================================================
-- Vertragsverwaltung - Datenbankschema für PostgreSQL
-- Datei: 01_schema_postgres.sql
--
-- Ausführen in pgAdmin:
--   Rechtsklick auf die Datenbank "vertragsverwaltung" -> Query Tool -> F5
--
-- Sicher wiederholbar: Vorhandene Tabellen werden NICHT gelöscht
-- (IF NOT EXISTS). Bereits eingetragene Daten bleiben erhalten.
-- =====================================================


-- =====================================================
-- 1. Tabellen ohne Fremdschlüssel (Stammdaten)
-- =====================================================

CREATE TABLE IF NOT EXISTS rolle (
    id_rolle     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bezeichnung  VARCHAR(50) NOT NULL,
    CONSTRAINT uq_rolle_bezeichnung UNIQUE (bezeichnung)
);

CREATE TABLE IF NOT EXISTS abteilung (
    id_abteilung  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bezeichnung   VARCHAR(100) NOT NULL,
    kostenstelle  VARCHAR(20),
    CONSTRAINT uq_abteilung_bezeichnung UNIQUE (bezeichnung)
);

CREATE TABLE IF NOT EXISTS vertragsart (
    id_vertragsart  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bezeichnung     VARCHAR(100) NOT NULL,
    CONSTRAINT uq_vertragsart_bezeichnung UNIQUE (bezeichnung)
);

CREATE TABLE IF NOT EXISTS laufzeit (
    id_laufzeit  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bezeichnung  VARCHAR(100) NOT NULL,
    CONSTRAINT uq_laufzeit_bezeichnung UNIQUE (bezeichnung)
);

CREATE TABLE IF NOT EXISTS vertragspartner (
    id_vertragspartner  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firmenname          VARCHAR(255) NOT NULL,
    strasse             VARCHAR(255),
    plz                 VARCHAR(10),
    ort                 VARCHAR(100),
    land                VARCHAR(100),
    email               VARCHAR(255),
    telefon             VARCHAR(50),
    notiz               TEXT
);


-- =====================================================
-- 2. Tabellen mit Fremdschlüsseln
-- =====================================================

CREATE TABLE IF NOT EXISTS benutzer (
    id_benutzer    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rolle       INT          NOT NULL,
    benutzername   VARCHAR(50)  NOT NULL,
    passwort_hash  VARCHAR(255) NOT NULL,
    vorname        VARCHAR(100) NOT NULL,
    nachname       VARCHAR(100) NOT NULL,
    email          VARCHAR(255) NOT NULL,
    aktiv          BOOLEAN      NOT NULL DEFAULT TRUE,
    erstellt_am    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_benutzer_benutzername UNIQUE (benutzername),
    CONSTRAINT uq_benutzer_email UNIQUE (email),
    CONSTRAINT fk_benutzer_rolle
        FOREIGN KEY (id_rolle) REFERENCES rolle (id_rolle)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Komposition: Ansprechpartner werden mit dem Vertragspartner gelöscht
CREATE TABLE IF NOT EXISTS ansprechpartner (
    id_ansprechpartner  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vertragspartner  INT          NOT NULL,
    vorname             VARCHAR(100),
    nachname            VARCHAR(100) NOT NULL,
    position            VARCHAR(100),
    email               VARCHAR(255),
    telefon             VARCHAR(50),
    CONSTRAINT fk_ansprechpartner_partner
        FOREIGN KEY (id_vertragspartner) REFERENCES vertragspartner (id_vertragspartner)
        ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS vertrag (
    id_vertrag             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vertragspartner     INT           NOT NULL,
    id_benutzer            INT           NOT NULL,   -- verantwortlicher Benutzer
    id_vertragsart         INT           NOT NULL,
    id_laufzeit            INT           NOT NULL,
    id_abteilung           INT           NOT NULL,
    vertragsnummer         VARCHAR(50)   NOT NULL,
    titel                  VARCHAR(255)  NOT NULL,
    beschreibung           TEXT,
    beginn_datum           DATE          NOT NULL,
    end_datum              DATE,                     -- NULL = unbefristet
    kuendigungsfrist_tage  INT,
    auto_verlaengerung     BOOLEAN       NOT NULL DEFAULT FALSE,
    verlaengerung_monate   INT,
    kosten                 NUMERIC(12,2),
    zahlungsintervall      VARCHAR(20),
    status                 VARCHAR(20)   NOT NULL DEFAULT 'entwurf',
    erstellt_am            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    geaendert_am           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_vertrag_vertragsnummer UNIQUE (vertragsnummer),
    CONSTRAINT fk_vertrag_partner
        FOREIGN KEY (id_vertragspartner) REFERENCES vertragspartner (id_vertragspartner)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_vertrag_verantwortlicher
        FOREIGN KEY (id_benutzer) REFERENCES benutzer (id_benutzer)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_vertrag_vertragsart
        FOREIGN KEY (id_vertragsart) REFERENCES vertragsart (id_vertragsart)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_vertrag_laufzeit
        FOREIGN KEY (id_laufzeit) REFERENCES laufzeit (id_laufzeit)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_vertrag_abteilung
        FOREIGN KEY (id_abteilung) REFERENCES abteilung (id_abteilung)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_vertrag_status
        CHECK (status IN ('entwurf', 'aktiv', 'gekuendigt', 'abgelaufen')),
    CONSTRAINT chk_vertrag_zahlungsintervall
        CHECK (zahlungsintervall IN ('einmalig', 'monatlich', 'quartalsweise', 'halbjaehrlich', 'jaehrlich')),
    CONSTRAINT chk_vertrag_datum
        CHECK (end_datum IS NULL OR end_datum > beginn_datum),
    CONSTRAINT chk_vertrag_kosten
        CHECK (kosten IS NULL OR kosten >= 0),
    CONSTRAINT chk_vertrag_kuendigungsfrist
        CHECK (kuendigungsfrist_tage IS NULL OR kuendigungsfrist_tage >= 0)
);

-- Komposition: Dokumente werden mit dem Vertrag gelöscht
CREATE TABLE IF NOT EXISTS dokument (
    id_dokument     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vertrag      INT          NOT NULL,
    id_benutzer     INT          NOT NULL,   -- hochgeladen von
    dateiname       VARCHAR(255) NOT NULL,
    dateipfad       VARCHAR(500) NOT NULL,
    hochgeladen_am  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_dokument_vertrag
        FOREIGN KEY (id_vertrag) REFERENCES vertrag (id_vertrag)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_dokument_benutzer
        FOREIGN KEY (id_benutzer) REFERENCES benutzer (id_benutzer)
        ON DELETE RESTRICT ON UPDATE CASCADE
);


-- =====================================================
-- 3. Indizes auf die Fremdschlüssel
--    (PostgreSQL legt sie im Gegensatz zu MySQL nicht automatisch an)
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_benutzer_rolle             ON benutzer (id_rolle);
CREATE INDEX IF NOT EXISTS idx_ansprechpartner_partner    ON ansprechpartner (id_vertragspartner);
CREATE INDEX IF NOT EXISTS idx_vertrag_partner            ON vertrag (id_vertragspartner);
CREATE INDEX IF NOT EXISTS idx_vertrag_verantwortlicher   ON vertrag (id_benutzer);
CREATE INDEX IF NOT EXISTS idx_vertrag_vertragsart        ON vertrag (id_vertragsart);
CREATE INDEX IF NOT EXISTS idx_vertrag_laufzeit           ON vertrag (id_laufzeit);
CREATE INDEX IF NOT EXISTS idx_vertrag_abteilung          ON vertrag (id_abteilung);
CREATE INDEX IF NOT EXISTS idx_dokument_vertrag           ON dokument (id_vertrag);
CREATE INDEX IF NOT EXISTS idx_dokument_benutzer          ON dokument (id_benutzer);
